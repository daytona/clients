# The client classes neither namespace exports: SDK 2.x builds a client only
# through the root (`Daytona().v0`, `Daytona().v2`). The root
# imports v2's from their submodules (`_sync`, `daytona`, `types`); the v0
# bundle step hides v0's behind private names. No suffixed alias either.
HIDDEN_CLIENTS = ("AsyncDaytona", "Daytona", "DaytonaConfig")

ROOT_EXPORTS += [f"{name}V2" for name in SHARED_WITH_V0]
