// Regenerate the Go code catalog from the sibling SDK's checked catalog:
// go run codes_generate.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type entry struct {
	code    string
	status  int
	sources []string
}

func generate() error {
	body, err := os.ReadFile("../sdk-typescript/src/v2/codes.ts")
	if err != nil {
		return fmt.Errorf("read catalog: %w", err)
	}
	statusPattern := regexp.MustCompile(`(?m)^  ([A-Z][A-Z0-9_]+): (\d+),`)
	entries := make([]entry, 0, 170)
	for _, match := range statusPattern.FindAllStringSubmatch(string(body), -1) {
		status, parseErr := strconv.Atoi(match[2])
		if parseErr != nil {
			return fmt.Errorf("parse status: %w", parseErr)
		}
		entries = append(entries, entry{code: match[1], status: status})
	}
	entries = append(entries, entry{code: "CLIENT_CLOSED"}, entry{code: "REQUEST_CANCELLED", status: 499})
	catalogPattern := regexp.MustCompile(`(?s)export const (\w+)_ERROR_CODES = Object.freeze\(\[(.*?)\] as const\)`)
	quotePattern := regexp.MustCompile(`'([A-Z][A-Z0-9_]+)'`)
	for _, catalog := range catalogPattern.FindAllStringSubmatch(string(body), -1) {
		for _, code := range quotePattern.FindAllStringSubmatch(catalog[2], -1) {
			for i := range entries {
				if entries[i].code == code[1] {
					entries[i].sources = append(entries[i].sources, catalog[1])
				}
			}
		}
	}
	for start := 0; start < len(entries); start += 20 {
		end := min(start+20, len(entries))
		if err := writeGroup(entries[start:end], start/20); err != nil {
			return err
		}
	}
	return writeDispatch(entries)
}

func goName(code string) string {
	parts := strings.Split(code, "_")
	for i, part := range parts {
		switch part {
		case "API", "CIDR", "ECR", "GPU", "ID", "TTL", "URL", "V0":
		default:
			parts[i] = part[:1] + strings.ToLower(part[1:])
		}
	}
	return strings.Join(parts, "")
}

func header() *bytes.Buffer {
	return bytes.NewBufferString("// Code generated by codes_generate.go; DO NOT EDIT.\n" +
		"// Copyright Daytona Platforms Inc.\n// SPDX-License-Identifier: Apache-2.0\n\npackage daytona\n\n")
}

func writeGroup(entries []entry, group int) error {
	out := header()
	for _, item := range entries {
		name := goName(item.code)
		fmt.Fprintf(out, "// Code%s is %s (%s).\nconst Code%s = %q\n\n",
			name, item.code, strings.Join(item.sources, ", "), name, item.code)
		if slices.Contains([]string{
			"BadRequest", "Conflict", "Forbidden", "Gone", "InternalServerError",
			"MethodNotAllowed", "NotFound", "PayloadTooLarge", "ServiceUnavailable",
			"UnprocessableEntity", "UnsupportedMediaType",
		}, name) {
			if name != "InternalServerError" {
				continue
			}
		}
		fmt.Fprintf(out, "// Err%s matches code %s, independently of its source.\nvar Err%s = codeSentinel{%q, %d}\n\n",
			name, item.code, name, item.code, item.status)
	}
	fmt.Fprintf(out, "func catalogStatus%d(source, code string) int {\nswitch code {\n", group)
	for _, item := range entries {
		fmt.Fprintf(out, "case %q:\n", item.code)
		if slices.Contains(item.sources, "GENERIC") {
			fmt.Fprintf(out, "return %d\n", item.status)
			continue
		}
		var conditions []string
		for _, source := range item.sources {
			value := "DAYTONA_" + source
			if source == "SDK" {
				value = source
			}
			conditions = append(conditions, "source == "+strconv.Quote(value))
			if source == "DAEMON" {
				conditions = append(conditions, `source == "SDK"`)
			}
		}
		if len(conditions) != 0 {
			fmt.Fprintf(out, "if %s { return %d }\n", strings.Join(conditions, " || "), item.status)
		}
	}
	fmt.Fprintln(out, "}\nreturn 0\n}")
	return writeGo(fmt.Sprintf("codes_catalog_%d.go", group), out.Bytes())
}

func writeDispatch(entries []entry) error {
	out := header()
	fmt.Fprintln(out, "func catalogStatus(source, code string) int {")
	for group := 0; group*20 < len(entries); group++ {
		fmt.Fprintf(out, "if status := catalogStatus%d(source, code); status != 0 { return status }\n", group)
	}
	fmt.Fprintln(out, "return 0\n}")
	return writeGo("codes_dispatch.go", out.Bytes())
}

func writeGo(path string, body []byte) error {
	formatted, err := format.Source(body)
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
