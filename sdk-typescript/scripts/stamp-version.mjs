// Writes src/version.ts from package.json so the published bundle reports the
// version the publish workflow stamped (it runs `npm version` before `build`).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const body = `// Generated by scripts/stamp-version.mjs from package.json — do not edit.\nexport const SDK_VERSION = '${version}'\n`
const target = join(root, 'src', 'version.ts')
let current = ''
try {
  current = readFileSync(target, 'utf8')
} catch {}
if (current !== body) writeFileSync(target, body)
