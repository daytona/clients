# The package root re-exports the generated module. While (re)generating, the
# file may be missing or stale, so the root's import of `_sync` is satisfied by
# a placeholder whose every twin name is a stub. Only when run as a script:
# tests import this module for its shared rules and must see the real `_sync`.
import types as _types


def _install_placeholder() -> None:
    placeholder = _types.ModuleType("daytona.v2._sync")

    def _missing(name: str) -> object:
        if name[:1].isupper():  # every twin name; the root imports them by name
            return type(name, (), {})
        raise AttributeError(name)

    placeholder.__getattr__ = _missing  # type: ignore[method-assign]
    placeholder.__path__ = []  # type: ignore[attr-defined]  # a package: `daytona.v2._sync._runtime` must still import
    sys.modules["daytona.v2._sync"] = placeholder


if __name__ == "__main__":
    _install_placeholder()

