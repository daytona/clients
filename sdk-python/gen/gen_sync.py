WRAPPED: set[str] = {name for names in TARGETS.values() for name in names}


def _twin(name: str) -> str:
    """The sync twin's name: the async class name without its ``Async`` prefix
    (``AsyncSandbox`` -> ``Sandbox``), the convention v0 and most dual-mode
    Python SDKs use."""
    return name.removeprefix("Async")


# Pure serialisers / rehydrators: no loop-owned state, safe on the caller's thread.
_LOOP_FREE = {"to_json", "ref", "from_json", "from_id", "connect"}


def _sync_doc(doc: str) -> str:
    """The full docstring for a sync twin: cross-references to wrapped async
    classes (``:class:`AsyncDockerService` ``) name the sync twin."""
    text = inspect.cleandoc(doc)
    # Example code in the async docstrings becomes sync code for the twin.
    text = re.sub(r"\basync with\b", "with", text)
    text = re.sub(r"\basync for\b", "for", text)
    text = re.sub(r"\bawait ", "", text)
    return re.sub(
        r"(?<![\w.])Async(" + "|".join(sorted(n.removeprefix("Async") for n in WRAPPED)) + r")(?![\w])",
        r"\1",
        text,
    )


def _doc_block(doc: str, indent: str) -> list[str]:
    """``doc`` as docstring source lines at ``indent`` (raw when it holds a backslash)."""
    text = _sync_doc(doc)
    prefix = 'r"""' if "\\" in text else '"""'
    lines = text.split("\n")
    if len(lines) == 1:
        return [f'{indent}{prefix}{lines[0]}"""']
    out = [f"{indent}{prefix}{lines[0]}"]
    out.extend(f"{indent}{line}" if line else "" for line in lines[1:])
    out.append(f'{indent}"""')
    return out


@dataclass
class Method:
    name: str
    kind: str  # "coro" | "agen" | "sync" | "property" | "classmethod_sync" | "staticmethod_sync"
    sig: inspect.Signature
    doc: str | None
    returns: object
    src_params: dict[str, str] | None = None  # param -> annotation source text
    src_returns: str | None = None  # return annotation source text


_SOURCE_ANNOTATIONS: dict[tuple[str, str, str], tuple[dict[str, str], str | None]] = {}
# (module, class, method) -> the @overload stub signatures, as source text of
# the parameter list (after `self`) and the return annotation, in order.
_OVERLOADS: dict[tuple[str, str, str], list[tuple[str, str]]] = {}
# (module, class) -> [(attr, annotation source | None, rhs source)]
_PUBLIC_ATTRS: dict[tuple[str, str], list[tuple[str, str | None, str]]] = {}


def _is_public_name(name: str) -> bool:
    """Public members have no leading underscore."""
    return not name.startswith("_")


def _index_source(module: str) -> None:
    import ast

    path = SRC / "daytona" / "v2" / f"{module}.py"
    tree = ast.parse(path.read_text())
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        attrs: dict[str, tuple[str | None, str]] = {}
        if any("dataclass" in ast.unparse(d) for d in node.decorator_list):
            for item in node.body:
                if (
                    isinstance(item, ast.AnnAssign)
                    and isinstance(item.target, ast.Name)
                    and _is_public_name(item.target.id)
                ):
                    attrs[item.target.id] = (ast.unparse(item.annotation), "")
        for item in node.body:
            if isinstance(item, ast.FunctionDef) and item.name == "__init__":
                for stmt in ast.walk(item):
                    targets = (
                        stmt.targets
                        if isinstance(stmt, ast.Assign)
                        else [stmt.target]
                        if isinstance(stmt, ast.AnnAssign)
                        else []
                    )
                    for target in targets:
                        if (
                            isinstance(target, ast.Attribute)
                            and isinstance(target.value, ast.Name)
                            and target.value.id == "self"
                            and _is_public_name(target.attr)
                        ):
                            ann = ast.unparse(stmt.annotation) if isinstance(stmt, ast.AnnAssign) else None
                            rhs = ast.unparse(stmt.value) if stmt.value is not None else ""
                            attrs.setdefault(target.attr, (ann, rhs))
        _PUBLIC_ATTRS[(module, node.name)] = [(k, v[0], v[1]) for k, v in attrs.items()]
        for item in node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and any(
                ast.unparse(d) == "overload" for d in item.decorator_list
            ):
                args = item.args
                rendered = ast.unparse(args)
                rendered = (
                    rendered[len("self, ") :] if rendered.startswith("self, ") else rendered[len("self") :]
                )
                _OVERLOADS.setdefault((module, node.name, item.name), []).append(
                    (rendered, ast.unparse(item.returns) if item.returns is not None else "None")
                )
                continue  # the implementation below carries the real annotations
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                params = {
                    a.arg: ast.unparse(a.annotation)
                    for a in [*item.args.posonlyargs, *item.args.args, *item.args.kwonlyargs]
                    if a.annotation is not None
                }
                positional = [*item.args.posonlyargs, *item.args.args]
                defaults: dict[str, str] = {}
                for a, d in zip(positional[len(positional) - len(item.args.defaults) :], item.args.defaults):
                    defaults[a.arg] = ast.unparse(d)
                for a, d in zip(item.args.kwonlyargs, item.args.kw_defaults):
                    if d is not None:
                        defaults[a.arg] = ast.unparse(d)
                params.update({f"={k}": v for k, v in defaults.items()})
                if item.args.vararg and item.args.vararg.annotation is not None:
                    params[item.args.vararg.arg] = ast.unparse(item.args.vararg.annotation)
                if item.args.kwarg and item.args.kwarg.annotation is not None:
                    params[item.args.kwarg.arg] = ast.unparse(item.args.kwarg.annotation)
                ret = ast.unparse(item.returns) if item.returns is not None else None
                _SOURCE_ANNOTATIONS[(module, node.name, item.name)] = (params, ret)


def _members(cls: type) -> list[Method]:
    out: list[Method] = []
    module = cls.__module__.rsplit(".", 1)[-1]
    if not any(k[0] == module for k in _SOURCE_ANNOTATIONS):
        _index_source(module)
    for name, raw in vars(cls).items():
        if not _is_public_name(name) and name not in ("__aenter__", "__aexit__"):
            continue
        if isinstance(raw, property):
            out.append(Method(name, "property", inspect.Signature(), raw.__doc__, _ret_of(raw.fget)))
            continue
        if isinstance(raw, classmethod):
            fn = raw.__func__
            sig = inspect.signature(fn)
            if any("Transport" in str(p.annotation) for p in sig.parameters.values()):
                continue  # internal constructor (from_api etc.), not a user-facing entry point
            out.append(Method(name, "classmethod_sync", sig, fn.__doc__, _ret_of(fn)))
            continue
        if isinstance(raw, staticmethod):
            fn = raw.__func__
            out.append(Method(name, "staticmethod_sync", inspect.signature(fn), fn.__doc__, _ret_of(fn)))
            continue
        if not callable(raw):
            continue
        if _is_internal_binder(raw):
            continue
        if inspect.isasyncgenfunction(raw):
            kind = "agen"
        elif inspect.iscoroutinefunction(raw):
            kind = "coro"
        else:
            kind = "sync"
        out.append(Method(name, kind, inspect.signature(raw), raw.__doc__, _ret_of(raw)))
    for m in out:
        params, ret = _SOURCE_ANNOTATIONS.get((module, cls.__name__, m.name), ({}, None))
        m.src_params, m.src_returns = params, ret
    return out


def _is_internal_binder(fn: object) -> bool:
    """`handle.bind(transport)` / `context.bind(execute, closer)`: wiring that
    takes a transport or async callables. The SDK calls these; users do not,
    and on the sync surface they could only be handed the wrong kind of
    object. Excluded from the generated twins."""
    try:
        sig = inspect.signature(fn)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return False
    text = " ".join(str(p.annotation) for p in sig.parameters.values())
    return "Transport" in text or "Awaitable" in text


def _ret_of(fn: object) -> object:
    try:
        hints = typing.get_type_hints(fn, include_extras=False)  # type: ignore[arg-type]
    except Exception:
        return None
    return hints.get("return")


def _mentions_wrapped(tp: object) -> bool:
    import re

    if isinstance(tp, type):
        return tp.__name__ in WRAPPED
    if isinstance(tp, str):
        return any(re.search(rf"(?<![\w.]){n}(?![\w])", tp) for n in WRAPPED)
    return any(_mentions_wrapped(a) for a in typing.get_args(tp))


def _direct_twin(tp: object) -> str | None:
    """If the return type is exactly one wrapped class, its Sync name."""
    if isinstance(tp, type) and tp.__name__ in WRAPPED:
        return _twin(tp.__name__)
    if isinstance(tp, str) and tp in WRAPPED:
        return _twin(tp)
    return None


def _sync_type_str(tp: object) -> str:  # introspection fallback when no source text is available
    if tp is None or tp is type(None):
        return "None"
    if isinstance(tp, type):
        return _twin(tp.__name__) if tp.__name__ in WRAPPED else tp.__name__
    return _swap_names(repr(tp).replace("typing.", ""))


_ASYNC_TO_SYNC_TYPES = (
    (r"\bAsyncIterator\[", "Iterator["),
    (r"\bAsyncIterable\[", "Iterable["),
    (r"\bAsyncGenerator\[", "Generator["),
    (r"\bAwaitable\[([^\]]+)\]", r"\1"),
)


def _sync_src_type(text: str | None) -> str:
    """Rewrite an annotation's source text for the sync surface."""
    import re

    if text is None:
        return "None"
    out = text
    for pattern, repl in _ASYNC_TO_SYNC_TYPES:
        out = re.sub(pattern, repl, out)
    for name in sorted(WRAPPED, key=len, reverse=True):
        out = re.sub(rf"(?<![\w.]){name}(?![\w])", _twin(name), out)
    return out


def _visible(tp: type) -> bool:
    mod = importlib.import_module(tp.__module__)
    return hasattr(mod, tp.__name__)


def _qual(tp: type) -> str:
    return f"{tp.__module__}.{tp.__name__}"


def _params_src(
    sig: inspect.Signature, *, drop_self: bool = True, src: dict[str, str] | None = None
) -> tuple[str, str, bool]:
    """Return (signature-params-source, forwarding-args-source, has_kw_only_marker)."""
    src = src or {}
    params = list(sig.parameters.values())
    if drop_self and params and params[0].name in ("self", "cls"):
        params = params[1:]
    decl: list[str] = []
    fwd: list[str] = []
    seen_kw_only = False
    positional_only = [p for p in params if p.kind is inspect.Parameter.POSITIONAL_ONLY]
    for index, p in enumerate(params):
        if p.kind is inspect.Parameter.VAR_POSITIONAL:
            decl.append(f"*{p.name}")
            fwd.append(f"*{p.name}")
            seen_kw_only = True
            continue
        if p.kind is inspect.Parameter.KEYWORD_ONLY and not seen_kw_only:
            decl.append("*")
            seen_kw_only = True
        if p.kind is inspect.Parameter.VAR_KEYWORD:
            decl.append(f"**{p.name}")
            fwd.append(f"**{p.name}")
            continue
        ann = f": {_sync_src_type(src[p.name])}" if p.name in src else ""
        forwarded = f"_rt.unwrap({p.name})" if p.name in src and _mentions_wrapped(src[p.name]) else p.name
        if f"={p.name}" in src:
            default = f" = {src[f'={p.name}']}"
        else:
            default = "" if p.default is inspect.Parameter.empty else f" = {_default_src(p.default)}"
        decl.append(f"{p.name}{ann}{default}")
        if p.kind is inspect.Parameter.KEYWORD_ONLY:
            fwd.append(f"{p.name}={forwarded}")
        else:
            fwd.append(forwarded)
        if positional_only and p is positional_only[-1]:
            decl.append("/")
    return ", ".join(decl), ", ".join(fwd), seen_kw_only


def _ann_src(ann: object) -> str:
    if isinstance(ann, str):
        return _swap_names(ann)
    if isinstance(ann, type):
        if ann.__name__ in WRAPPED:
            return _twin(ann.__name__)
        return (
            ann.__name__
            if ann.__module__ == "builtins"
            else f"_async.{ann.__name__}"
            if _visible(ann)
            else _qual(ann)
        )
    return _swap_names(repr(ann).replace("typing.", ""))


def _swap_names(text: str) -> str:
    for name in sorted(WRAPPED, key=len, reverse=True):
        text = text.replace(f"'{name}'", f"'{_twin(name)}'").replace(f'"{name}"', f'"{_twin(name)}"')
    return text


def _default_src(value: object) -> str:
    if isinstance(value, (str, int, float, bool)) or value is None:
        return repr(value)
    if isinstance(value, tuple):
        return repr(value)
    return "..."


def _emit_class(module: str, cls: type) -> str:
    name = cls.__name__
    if not any(k[0] == module for k in _PUBLIC_ATTRS):
        _index_source(module)
    lines: list[str] = []
    lines.append(f"class {_twin(name)}:")
    lines.extend(_doc_block(cls.__doc__ or f"Synchronous {_twin(name)}.", "    "))
    lines.append("")
    lines.append(f"    _async_type = _async.{name}")
    lines.append("")
    if name == "AsyncDaytona":
        lines.append("    def __init__(self, config: Optional[_async.DaytonaConfig] = None) -> None:")
        lines.append("        self._bridge = SyncBridge(name='Daytona', on_exit=self.close)")
        # The sync facade drives the async client, so it must claim its own
        # X-Daytona-Source label or every sync Daytona request reads as async.
        lines.append(f"        self._impl = _async.{name}(config, _source='sdk-python')")
        lines.append("")
    else:
        # Construction is internal: the SDK wraps the async object it returned.
        lines.append(f"    def __init__(self, _impl: _async.{name}, _bridge: SyncBridge) -> None:")
        lines.append("        self._impl = _impl")
        lines.append("        self._bridge = _bridge")
        lines.append("")
    lines.append("    def __repr__(self) -> str:")
    lines.append(f"        return f'{_twin(name)}({{self._impl!r}})'")
    lines.append("")
    lines.append("    def __eq__(self, other: object) -> bool:")
    lines.append(f"        return isinstance(other, {_twin(name)}) and other._impl == self._impl")
    lines.append("")
    lines.append("    def __hash__(self) -> int:")
    lines.append("        return hash(self._impl)")
    lines.append("")
    for attr, ann, rhs in _PUBLIC_ATTRS.get((module, name), []):
        ann_text = ann or _infer_attr_type(module, cls, attr, rhs)
        lines.append("    @property")
        lines.append(f"    def {attr}(self) -> {_sync_src_type(ann_text)}:")
        lines.append(f"        return {_wrap_expr(ann_text, f'self._impl.{attr}', 'self._bridge')}")
        lines.append("")

    direct_properties: frozenset[str] = getattr(cls, "_SYNC_DIRECT_PROPERTIES", frozenset())
    loop_variants: Mapping[str, str] = getattr(cls, "_SYNC_LOOP_VARIANTS", {})
    after_wraps: Mapping[str, str] = getattr(cls, "_SYNC_AFTER_WRAP", {})
    for m in sorted(_members(cls), key=lambda m: (m.kind == "property", m.name)):
        if name == "AsyncDaytona" and m.name == "close":
            lines.append("    def close(self) -> None:")
            lines.append(
                '        """Close HTTP resources, then stop the bridge loop. Idempotent; safe from any thread."""'
            )
            lines.append("        self._bridge.close(self._impl.close)")
            lines.append("")
            continue
        if m.name == "__aenter__":
            lines.append("    def __enter__(self) -> Self:")
            lines.append("        self._bridge.call(self._impl.__aenter__)")
            lines.append("        return self")
            lines.append("")
            continue
        if m.name == "__aexit__":
            lines.append("    def __exit__(self, *exc: object) -> None:")
            if name == "AsyncDaytona":
                lines.append("        self.close()")
            else:
                lines.append("        self._bridge.call(lambda: self._impl.__aexit__(*exc))")
            lines.append("")
            continue
        ret = _sync_src_type(m.src_returns) if m.src_returns is not None else _sync_type_str(m.returns)
        if m.kind == "property":
            # A property on an async class is computed state the loop mutates
            # (a watch's exit_error / overflow_count): read it ON the loop, so
            # a sync caller never observes it mid-update from another thread.
            # Plain __init__ attributes (emitted above) are set once and read
            # freely, and so are the properties a class lists in
            # `_SYNC_DIRECT_PROPERTIES` (fields of a snapshot the loop replaces
            # whole), which stay readable after the client closes.
            lines.append("    @property")
            lines.append(f"    def {m.name}(self) -> {ret}:")
            if m.doc:
                lines.extend(_doc_block(m.doc, "        "))
            if m.name in direct_properties:
                inner = f"self._impl.{m.name}"
            else:
                inner = f"self._bridge.call_sync(lambda: self._impl.{m.name})"
            lines.append(f"        return {_wrap_expr(m.src_returns or m.returns, inner, 'self._bridge')}")
            lines.append("")
            continue
        decl, fwd, _ = _params_src(m.sig, src=m.src_params)
        if m.kind in ("classmethod_sync", "staticmethod_sync"):
            # Rehydration classmethods (from_json / from_id) build an UNBOUND
            # async handle: no transport, no I/O until it is connected through
            # a client (`sandbox.process.connect(handle.to_json())`). The sync
            # twin mirrors the async signature exactly and carries no bridge;
            # any I/O method on it raises the same "not bound" error the async
            # handle does, before ever needing a loop.
            lines.append("    @classmethod")
            lines.append(f"    def {m.name}(cls, {decl}) -> {ret}:")
            if m.doc:
                lines.extend(_doc_block(m.doc, "        "))
            lines.append(
                f"        return {_wrap_expr(m.src_returns or m.returns, f'_async.{name}.{m.name}({fwd})', '_rt.UNBOUND')}"
            )
            lines.append("")
            continue
        for stub_params, stub_ret in _OVERLOADS.get((module, name, m.name), []):
            # mirror the async source's @overload narrowing on the sync twin
            lines.append("    @overload")
            lines.append(
                f"    def {m.name}(self{', ' if stub_params else ''}{_sync_src_type(stub_params)}) -> {_sync_src_type(stub_ret)}: ..."
            )
            lines.append("")
        sig = f"self{', ' if decl else ''}{decl}"
        lines.append(f"    def {m.name}({sig}) -> {ret}:")
        if m.doc:
            lines.extend(_doc_block(m.doc, "        "))
        if m.kind == "coro" and (m.src_returns or "") == "Self":
            # A fluent method returns the SAME handle (`-> Self`): the sync twin
            # must return itself, not a second wrapper around the same impl
            # (`sandbox.wait() is sandbox` holds on both sides).
            lines.append(f"        self._bridge.call(lambda: self._impl.{m.name}({fwd}))")
            lines.append("        return self")
        elif m.kind == "coro":
            # A method listed in the class's `_SYNC_LOOP_VARIANTS` (a watch's
            # stop()) can be called from a callback the SDK runs on the loop
            # thread, where blocking on the loop is impossible: there it calls
            # the named non-blocking method instead.
            loop_variant = loop_variants.get(m.name)
            if loop_variant is not None:
                lines.append("        if self._bridge.on_loop_thread():")
                lines.append(f"            return self._impl.{loop_variant}({fwd})")
            inner = f"self._bridge.call(lambda: self._impl.{m.name}({fwd}))"
            after_wrap = after_wraps.get(m.name)
            if after_wrap is not None:
                # A method listed in the class's `_SYNC_AFTER_WRAP` returns an
                # object that waits for its synchronous twin (a watch holds its
                # callbacks until the caller has a handle): once the twin is
                # built, the named method of the async object is posted to the
                # loop, without waiting, as the twin returns.
                lines.append(
                    f"        result = {_wrap_expr(m.src_returns or m.returns, inner, 'self._bridge')}"
                )
                lines.append(f"        self._bridge.post(result._impl.{after_wrap})")
                lines.append("        return result")
            else:
                lines.append(
                    f"        return {_wrap_expr(m.src_returns or m.returns, inner, 'self._bridge')}"
                )
        elif m.kind == "agen":
            inner = f"self._bridge.iterate(self._impl.{m.name}({fwd}))"
            lines.append(f"        return {_wrap_expr(m.src_returns or m.returns, inner, 'self._bridge')}")
        elif m.name in _LOOP_FREE:
            lines.append(
                f"        return {_wrap_expr(m.src_returns or m.returns, f'self._impl.{m.name}({fwd})', 'self._bridge')}"
            )
        else:
            # A plain method on an async class may still touch loop-owned state
            # (the interpreter's gate registry, a watch's asyncio.Queue). Run it
            # on the loop like everything else so that state is never shared
            # across caller threads.
            inner = f"self._bridge.call_sync(lambda: self._impl.{m.name}({fwd}))"
            lines.append(f"        return {_wrap_expr(m.src_returns or m.returns, inner, 'self._bridge')}")
        lines.append("")
    return "\n".join(lines)


def _container_twin(ret: str) -> tuple[str, str] | None:
    """('list'|'tuple'|'iter'|'page', SyncName) when ret is a container of exactly one wrapped class."""
    import re

    m = re.fullmatch(r"(list|List|Sequence)\[(\w+)\]", ret)
    if m and m.group(2) in WRAPPED:
        return ("list", _twin(m.group(2)))
    m = re.fullmatch(r"(tuple|Tuple)\[(\w+), \.\.\.\]", ret)
    if m and m.group(2) in WRAPPED:
        return ("tuple", _twin(m.group(2)))
    m = re.fullmatch(r"(Iterator|AsyncIterator)\[(\w+)\]", ret)
    if m and m.group(2) in WRAPPED:
        return ("iter", _twin(m.group(2)))
    m = re.fullmatch(r"(ListResult|SearchResult)\[(\w+)\]", ret)
    if m and m.group(2) in WRAPPED:
        return ("page", _twin(m.group(2)))
    return None


def _infer_attr_type(module: str, cls: type, attr: str, rhs: str) -> str:
    """Type of an unannotated `self.attr = <rhs>` in __init__.

    Resolves `info.field` / `param` against the constructor's own annotations
    and the info dataclass's fields; anything else must be annotated at the
    source, which is reported rather than guessed.
    """
    import ast
    import dataclasses

    hints = typing.get_type_hints(cls.__init__)
    if rhs in hints:
        return _type_to_src(hints[rhs])
    if rhs.startswith("info.") and "info" in hints:
        info_cls = hints["info"]
        for field in dataclasses.fields(info_cls) if dataclasses.is_dataclass(info_cls) else []:
            if field.name == rhs[len("info.") :]:
                return _type_to_src(typing.get_type_hints(info_cls)[field.name])
    m = ast.parse(rhs).body[0].value if rhs else None  # type: ignore[attr-defined]
    if isinstance(m, ast.BoolOp) and all(isinstance(v, ast.Name) and v.id in hints for v in m.values):
        return " | ".join(_type_to_src(hints[v.id]) for v in m.values)  # type: ignore[attr-defined]
    # `self.images = ImageService(...)`: a namespace object of a known class
    if isinstance(m, ast.Call) and isinstance(m.func, ast.Name):
        return m.func.id
    # `self.secrets = self.secret`: an alias of an earlier attribute
    if isinstance(m, ast.Attribute) and isinstance(m.value, ast.Name) and m.value.id == "self":
        for other, ann, other_rhs in _PUBLIC_ATTRS.get((module, cls.__name__), []):
            if other == m.attr:
                return ann or _infer_attr_type(module, cls, other, other_rhs)
    raise SystemExit(
        f"gen_sync: cannot type public attribute {cls.__name__}.{attr} = {rhs!r}; annotate it in {module}.py"
    )


def _type_to_src(tp: object) -> str:
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if origin is None:
        if tp is type(None):
            return "None"
        if isinstance(tp, type):
            return tp.__name__
        if isinstance(tp, typing.TypeVar):
            return tp.__name__
        if isinstance(tp, typing.ForwardRef):
            return tp.__forward_arg__
        return repr(tp).replace("typing.", "")
    name = getattr(origin, "__name__", None) or repr(origin).replace("typing.", "")
    if name in ("Union", "UnionType"):
        return " | ".join(_type_to_src(a) for a in args)
    if name == "Literal":
        return "Literal[" + ", ".join(repr(a) for a in args) + "]"
    return f"{name}[{', '.join(_type_to_src(a) for a in args)}]"


def _wrap_expr(ret: object, inner: str, bridge: str) -> str:
    """The expression that turns an async result into the declared Sync type.

    - no SDK handle in the return type: pass the value through, fully typed;
    - exactly one handle class: construct its Sync twin directly (typed);
    - list/tuple/iterator/page of one handle class: typed container helper;
    - anything else containing handles: the erased registry walk in ``_wrap``.
    """
    if ret is None or not _mentions_wrapped(ret):
        return inner
    twin = _direct_twin(ret)
    if twin is not None:
        return f"{twin}({inner}, {bridge})"
    if isinstance(ret, str):
        container = _container_twin(ret)
        if container is not None:
            kind, name = container
            if kind == "list":
                return f"_rt.wrap_list({inner}, {bridge}, {name})"
            if kind == "tuple":
                return f"_rt.wrap_tuple({inner}, {bridge}, {name})"
            if kind == "iter":
                return f"_rt.wrap_iter({inner}, {bridge}, {name})"
            return f"_rt.wrap_page({inner}, {bridge}, {name})  # type: ignore[return-value]"
    return f"_rt.wrap({inner}, {bridge})  # type: ignore[return-value]"


def _alias(module: str) -> str:
    # `_m_x`, never `__x`: a leading double underscore would be name-mangled
    # inside the generated class bodies.
    return f"_m_{module.lstrip('_')}"


def _module_of(name: str) -> str:
    for module, names in TARGETS.items():
        if name in names:
            return module
    raise KeyError(name)


def render_module(module: str, names: list[str]) -> str:
    import re

    mod = importlib.import_module(f"daytona.v2.{module}")
    body = "\n\n".join(_emit_class(module, getattr(mod, n)) for n in names)
    # Private annotation names (`_WatchCallback`, `_OMITTED`) are not reached
    # by `import *`; import each from the async module explicitly.
    privates = sorted(
        {
            n
            for n in set(re.findall(r"(?<![\w.])(_[A-Za-z]\w*)", body))
            if hasattr(mod, n) and n not in ("_async", "_rt")
        }
    )
    private_imports = f"from ..{module} import {', '.join(privates)}\n" if privates else ""
    # Sync twins from OTHER modules that this module names. Imported under
    # TYPE_CHECKING for annotations; constructed at runtime through a lazy
    # resolver so the package stays cycle-free.
    # Docstrings are prose: a bare twin name there (``Sandbox``) is not a use.
    code = re.sub(r'r?"""(?:[^"\\]|\\.|"(?!""))*"""', "", body)
    others = sorted(
        n for n in WRAPPED if n not in names and re.search(rf"(?<![\w.]){_twin(n)}(?![\w])", code)
    )
    twin_imports = ""
    if others:
        by_module: dict[str, list[str]] = {}
        for n in others:
            by_module.setdefault(_module_of(n), []).append(n)
        lines = ["", "if TYPE_CHECKING:"]
        for m, ns in sorted(by_module.items()):
            lines.append(f"    from .{m} import {', '.join(_twin(n) for n in ns)}")
        twin_imports = "\n".join(lines) + "\n"
        body = _localize_foreign_twins(body, others)
    return (
        HEADER.format(module=module, private_imports=private_imports, twin_imports=twin_imports) + body + "\n"
    )


def _localize_foreign_twins(body: str, others: list[str]) -> str:
    """Every method body that constructs a twin from another module gets a
    function-local import of it, placed right before the `return`.

    Runs at call time, when every twin module is loaded, so the package has
    no import cycle; the name stays real, so mypy types the construction.
    """
    import re

    out: list[str] = []
    pending: list[str] = []  # a multi-line `return (...)` is scanned as one unit
    for line in body.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("return "):
            # gather the whole statement (balanced parentheses) to find twins used as values
            depth = line.count("(") - line.count(")")
            statement = line
            pending = []
            if depth > 0:
                pending = [line]
                out.append("__PENDING__")
                continue
            used = sorted(n for n in others if re.search(rf"(?<![\w.\"]){_twin(n)}(?![\w])", statement))
            if used:
                indent = line[: len(line) - len(stripped)]
                by_module: dict[str, list[str]] = {}
                for n in used:
                    by_module.setdefault(_module_of(n), []).append(n)
                for m, ns in sorted(by_module.items()):
                    out.append(f"{indent}from .{m} import {', '.join(_twin(n) for n in ns)}")
                out.append("")  # ruff wants a blank line after a local import block
            out.append(line)
            continue
        if pending:
            pending.append(line)
            depth = sum(l.count("(") - l.count(")") for l in pending)
            if depth <= 0:
                statement = "\n".join(pending)
                used = sorted(n for n in others if re.search(rf"(?<![\w.\"]){_twin(n)}(?![\w])", statement))
                first = pending[0]
                indent = first[: len(first) - len(first.lstrip())]
                imports: list[str] = []
                if used:
                    by_module = {}
                    for n in used:
                        by_module.setdefault(_module_of(n), []).append(n)
                    for m, ns in sorted(by_module.items()):
                        imports.append(f"{indent}from .{m} import {', '.join(_twin(n) for n in ns)}")
                    imports.append("")
                # replace the placeholder with imports + the whole statement
                idx = len(out) - 1 - out[::-1].index("__PENDING__")
                out[idx : idx + 1] = imports + pending
                pending = []
            continue
        out.append(line)
    return "\n".join(out)


def render_init() -> str:
    lines = [
        *LICENSE_HEADER.rstrip("\n").split("\n"),
        "",
        '"""GENERATED by gen/gen_sync.py. Do not edit.',
        "",
        "The synchronous SDK surface, one module per async module. ``_runtime.py``",
        "is the hand-written glue; everything else in this package is emitted.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for module in TARGETS:
        lines.append(f"from .. import {module} as {_alias(module)}")
    lines.append("from . import _runtime as _rt")
    for module, names in TARGETS.items():
        lines.append(f"from .{module} import {', '.join(_twin(n) for n in names)}")
    lines += [
        "",
        "# async class -> Sync twin; _rt.wrap()/unwrap() walk this.",
        "_rt.REGISTRY.update(",
        "    {",
    ]
    for module, names in TARGETS.items():
        for n in names:
            twin = _twin(n)
            lines.append(f"        {_alias(module)}.{n}: {twin},")
    lines += ["    }", ")", "", "__all__ = ["]
    for names in TARGETS.values():
        for n in names:
            lines.append(f'    "{_twin(n)}",')
    lines.append("]")
    return "\n".join(lines) + "\n"


def generate() -> dict[Path, str]:
    files: dict[Path, str] = {OUT / "__init__.py": render_init()}
    for module, names in TARGETS.items():
        files[OUT / f"{module}.py"] = render_module(module, names)
    return {path: _ruff(text, path) for path, text in files.items()}


def _ruff(text: str, path: Path) -> str:
    """Normalise emitted source with the repo's own ruff config, so the
    committed tree is byte-identical to what a fresh run produces."""
    import subprocess

    ruff = [sys.executable, "-m", "ruff"]
    fixed = subprocess.run(
        # UP037 misreads `Literal['x']` (as unparsed by ast) as a quoted forward
        # reference and strips the quotes, turning the literal into a bare name.
        [*ruff, "check", "--fix", "--fix-only", "--exit-zero", "-q", "--stdin-filename", str(path), "-"],
        input=text,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    ).stdout
    return subprocess.run(
        [*ruff, "format", "-q", "--stdin-filename", str(path), "-"],
        input=fixed,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    ).stdout


def main(argv: list[str]) -> int:
    files = generate()
    generated_names = {p.name for p in files}
    if "--check" in argv:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        extra = (
            [p for p in OUT.glob("*.py") if p.name not in generated_names | HANDWRITTEN]
            if OUT.exists()
            else []
        )
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        for p in extra:
            print(f"unexpected: {p.relative_to(ROOT)}")
        return 1 if stale or extra else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in files.items():
        p.write_text(text)
    for p in OUT.glob("*.py"):
        if p.name not in generated_names | HANDWRITTEN:
            p.unlink()
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
