import { readFile, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import { withNamedArguments } from './optional-arguments.mjs';

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
const root = new URL('../', import.meta.url);
const mapping = JSON.parse(await readFile(new URL('mapping/mapping.json', root), 'utf8'));
const cell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');
const code = (text) => {
  const fence = '`'.repeat(1 + Math.max(0, ...[...text.matchAll(/`+/g)].map(([run]) => run.length)));
  return `${fence}${cell(text)}${fence}`;
};
function receiverName(receiver, language) {
  const metadata = mapping.receivers[receiver];
  if (metadata.parent) return `${receiverName(metadata.parent, language)}.${metadata.attr[language]}`;
  return language === 'py' ? receiver.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`) : receiver;
}
// Readable section titles for the public guide: the Python and TypeScript
// spellings of the receiver, for example `client.warm_pool` / `client.warmPool`.
function heading(receiver) {
  const py = receiverName(receiver, 'py');
  const ts = receiverName(receiver, 'ts');
  return py === ts ? `\`${ts}\`` : `\`${py}\` / \`${ts}\``;
}

const lines = [
  '<!-- Generated by scripts/gen-guide.mjs from mapping/mapping.json. Do not edit. -->',
  '# Migrate from SDK 0.x to SDK 2.x',
  '',
  '## Upgrade the package and stay on v0',
  '',
  'Upgrading to SDK 2.x does not move your workloads to v2. Use the root client’s',
  '`.v0` namespace to keep calling the v0 platform. Resource imports move to the',
  'v0 module, and so do the shared error classes (`DaytonaError`,',
  '`DaytonaNotFoundError`, …). Client and configuration imports stay at the root.',
  '',
  'The v0 error classes keep the 0.x constructor and fields, and every error the',
  '`.v0` client raises is one of them, so `except` / `catch` code works as before.',
  'The 2.x root error classes are markers that also catch v2 errors but take only a',
  'message and carry no 0.x fields: when you move calls to `.v2`, import the errors',
  'from the root again.',
  '',
  'The root `Daytona()` constructor no longer checks for missing credentials: the',
  'v0 client is built, and a missing API key reported, on the first `.v0` access (a',
  'rejected key still fails on the first request, as in 0.x). If your code wraps',
  'the constructor in `try` to detect missing credentials, access `.v0` inside that',
  '`try`; the upgrade tool marks these constructions with a FIXME.',
  '',
  '| Language | Before | SDK 2.x, same platform |',
  '| --- | --- | --- |',
  '| Python | `daytona.create()` | `daytona.v0.create()` |',
  '| Python | `from daytona import Sandbox` | `from daytona.v0 import Sandbox` |',
  '| TypeScript | `daytona.create()` | `daytona.v0.create()` |',
  "| TypeScript | `import { Sandbox } from '@daytonaio/sdk'` | `import { Sandbox } from '@daytona/sdk/v0'` |",
  '',
  'Install the SDK release you migrate to, with the v0 SDK extra for Python. Until SDK 2.0.0',
  "is out, that is the exact alpha, e.g. `uv add 'daytona[v0-sdk]==2.0.0aN'` and",
  '`npm install @daytona/sdk@2.0.0-alpha.N`; after it, `uv add ' + `'${mapping.packages.py.requirement}'\`` + ' and',
  `\`npm install ${mapping.packages.ts.new}@${mapping.packages.ts.range}\`.`,
  'SDK 2.x targets Daytona Cloud. For a custom API URL, stay on SDK 0.x.',
  '',
  'Python only: `DaytonaConfig` is a dataclass in SDK 2.x, not a pydantic model:',
  'replace `model_dump()`/`dict()` with `dataclasses.asdict(cfg)`,',
  '`model_copy()`/`copy()` with `dataclasses.replace(cfg, …)`, and',
  '`model_validate()`/`parse_obj()` with `DaytonaConfig(**data)`.',
  '',
  'Run the migration tool from your project directory:',
  '',
  '```sh',
  'npx @daytona/upgrade  # TypeScript or JavaScript',
  'uvx daytona-upgrade  # Python',
  '```',
  '',
  'Each tool release migrates to the SDK release of the same version. Until SDK 2.0.0',
  'is out, run the exact alpha you are migrating to, e.g. `npx @daytona/upgrade@2.0.0-alpha.N`',
  'or `uvx daytona-upgrade@2.0.0aN`.',
  '',
  'The tools update dependencies and proven client calls. Review each',
  '`FIXME(daytona-upgrade)` item before running the result.',
  '',
  '## Move a workflow to v2',
  '',
  'Move one sandbox workflow at a time. Do not mix v0 and v2 handles within a',
  'workflow. Run either tool with `--suggest-v2` to add suggestions without',
  'rewriting calls or dependencies. Use `--remove-suggestions` to remove them.',
  '',
  '<a id="data"></a>',
  '',
  '### What does not carry over to v2',
  '',
  ...mapping.dataTraps.map(({ text }) => `- ${text}`),
  '',
  'In the tables, `{client}` is the root client (for example, `daytona`), and',
  '`{sandbox}` is a v2 sandbox. Other identifiers stand for your values or handles.',
  'The call forms show arguments to review, not automatic replacements. In Python,',
  'await async operations, but not synchronous handle-binding calls. Sync clients',
  'use the same method names.',
  'In TypeScript, await asynchronous calls. `none` means no equivalent SDK method;',
  'the notes describe an alternative where one exists.',
  '',
];

for (const [receiver, metadata] of Object.entries(mapping.receivers)) {
  const entries = mapping.suggestions.filter((entry) => entry.receiver === receiver);
  if (entries.length === 0) continue;
  const anchors = new Set(entries.map(({ anchor }) => anchor));
  if (anchors.size !== 1) throw new TypeError(`${receiver}: expected one section anchor`);
  lines.push(`<a id="${entries[0].anchor}"></a>`, `## ${heading(receiver)}`, '');
  for (const note of metadata.notes ?? []) lines.push(note, '');
  for (const [language, heading] of [['py', 'Python'], ['ts', 'TypeScript']]) {
    const rows = entries.filter((entry) => entry.v0[language] !== null);
    if (rows.length === 0) continue;
    lines.push(`### ${heading}`, '', '| v0 call | v2 equivalent | Notes |', '| --- | --- | --- |');
    for (const entry of rows) {
      const before = `${receiverName(receiver, language)}.${entry.v0[language]}(...)`;
      const after = entry.v2[language] === null ? 'None' : code(withNamedArguments(entry.v2[language]));
      const notes = [entry.v2[language] === null ? 'none' : entry.category, ...entry.notes[language]].map(cell).join('; ');
      lines.push(`| ${code(before)} | ${after} | ${notes} |`);
    }
    lines.push('');
  }
}

const output = new URL('MIGRATION.md', root);
const rendered = `${lines.join('\n').trimEnd()}\n`;
if (values.check) {
  let committed;
  try {
    committed = await readFile(output, 'utf8');
  } catch (error) {
    if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT') throw error;
  }
  if (committed !== rendered) {
    console.error('MIGRATION.md is stale; run node upgrade/scripts/gen-guide.mjs');
    process.exitCode = 1;
  } else console.log('MIGRATION.md is up to date');
} else {
  await writeFile(output, rendered);
  console.log(`Generated MIGRATION.md (${mapping.suggestions.length} suggestions)`);
}
