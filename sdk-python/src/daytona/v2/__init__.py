# Defined only at runtime: a module-level __getattr__ makes type checkers treat
# every attribute as present, which would hide `from daytona.v2 import Daytona`
# from mypy / pyright.
if not TYPE_CHECKING:

    def __getattr__(name: str) -> object:
        """Guide imports of the client classes, which only the root builds.

        An ``ImportError``, not an ``AttributeError``: for ``from daytona.v2
        import Daytona`` CPython replaces an ``AttributeError`` from a module
        ``__getattr__`` with its generic "cannot import name" message.
        """
        from ._exports import HIDDEN_CLIENTS

        if name in HIDDEN_CLIENTS or (name.endswith("V2") and name[:-2] in HIDDEN_CLIENTS):
            from .._client import _client_not_exported

            raise ImportError(_client_not_exported("v2", name), name=__name__)
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
