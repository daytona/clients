"""Generate the synchronous SDK surface from the async implementation.

Reads the async classes by introspection and emits ``daytona/v2/_sync/*.py``:
one sync ``<Name>`` wrapper per public ``Async<Name>`` class that carries async
methods. Each
wrapper holds the async object and a :class:`SyncBridge`; every coroutine
method becomes a blocking call, every async generator a plain iterator, and
every returned SDK handle is wrapped into its own sync twin (``AsyncSandbox``
-> ``Sandbox``).

The output is committed. ``tests/test_sync_surface.py`` fails when it is
stale, so the two surfaces cannot drift:

    python gen/gen_sync.py            # regenerate
    python gen/gen_sync.py --check    # exit 1 if the tree differs
"""

